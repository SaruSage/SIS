export function icone(nome, tamanho) {
  const caminho = CAMINHOS[nome] || CAMINHOS.home;
  const t = tamanho || 18;
  return (
    '<svg class="icone-svg" width="' + t + '" height="' + t + '" ' +
    'viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
    'stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" ' +
    'aria-hidden="true">' + caminho + '</svg>'
  );
}

export function substituirIcones(raiz) {
  const escopo = raiz || document;
  escopo.querySelectorAll("[data-icone]").forEach((el) => {
    const nome = el.dataset.icone;
    const tamanho = parseInt(el.dataset.tamanho, 10) || 18;
    el.innerHTML = icone(nome, tamanho);
  });
}
